/* Text for script-made strings: tr("load.read", {done: 3, total: 9}). */
function tr(key, vars) {
  const s = STR.en[key];
  if (s === undefined) return key;
  return vars ? s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? vars[k] : "")) : s;
}
